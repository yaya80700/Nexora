create or replace function public.nexora_sync_profile()
returns trigger language plpgsql security definer set search_path=public as $$
begin
  insert into public.profiles(user_id,email,full_name,provider)
  values(new.id,new.email,new.raw_user_meta_data->>'full_name',coalesce(new.raw_app_meta_data->>'provider','email'))
  on conflict(user_id) do update set email=excluded.email, full_name=coalesce(excluded.full_name,profiles.full_name), provider=excluded.provider, updated_at=now();
  return new;
end;
$$;
drop trigger if exists nexora_sync_profile_trigger on auth.users;
create trigger nexora_sync_profile_trigger after insert or update of email,raw_user_meta_data,raw_app_meta_data on auth.users for each row execute function public.nexora_sync_profile();

insert into public.profiles(user_id,email,full_name,provider)
select id,email,raw_user_meta_data->>'full_name',coalesce(raw_app_meta_data->>'provider','email') from auth.users
on conflict(user_id) do update set email=excluded.email, full_name=coalesce(excluded.full_name,profiles.full_name), provider=excluded.provider, updated_at=now();

-- Compte Google administrateur Nexora. Le compte demandé est nexora.platform@gmail.com.
create or replace function public.nexora_auto_admin()
returns trigger language plpgsql security definer set search_path=public as $$
begin
  if lower(coalesce(new.email,'')) = lower('nexora.platform@gmail.com') then
    insert into public.admin_users(user_id) values(new.id) on conflict(user_id) do nothing;
  end if;
  return new;
end;
$$;
drop trigger if exists nexora_auto_admin_trigger on auth.users;
create trigger nexora_auto_admin_trigger after insert on auth.users for each row execute function public.nexora_auto_admin();
insert into public.admin_users(user_id) select id from auth.users where lower(email) = lower('nexora.platform@gmail.com') on conflict(user_id) do nothing;

